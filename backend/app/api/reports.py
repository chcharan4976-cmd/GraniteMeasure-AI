import json
from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select, func
from datetime import datetime, timezone

from app.database import get_db
from app.models import (
    GraniteBlock, MeasurementResult, SeigniorageAssessment,
    BlockImage, CaptureSession, Quarry, AuditLog
)

router = APIRouter(prefix="/api/v1/reports", tags=["Reports"])


@router.get("/{block_id}")
async def generate_report(block_id: int, db: AsyncSession = Depends(get_db)):
    """Generate a comprehensive report for a granite block."""
    # Get block
    result = await db.execute(select(GraniteBlock).where(GraniteBlock.id == block_id))
    block = result.scalar_one_or_none()
    if not block:
        raise HTTPException(status_code=404, detail="Block not found")

    # Get quarry
    quarry = None
    if block.quarry_id:
        q_result = await db.execute(select(Quarry).where(Quarry.id == block.quarry_id))
        quarry = q_result.scalar_one_or_none()

    # Get measurement
    meas_result = await db.execute(
        select(MeasurementResult).where(MeasurementResult.block_id == block_id)
    )
    measurement = meas_result.scalar_one_or_none()

    # Get seigniorage assessment
    assess_result = await db.execute(
        select(SeigniorageAssessment).where(SeigniorageAssessment.block_id == block_id)
    )
    assessment = assess_result.scalar_one_or_none()

    # Get image count
    img_result = await db.execute(
        select(func.count(BlockImage.id)).where(BlockImage.block_id == block_id)
    )
    image_count = img_result.scalar() or 0

    # Get audit logs
    audit_result = await db.execute(
        select(AuditLog)
        .where(AuditLog.entity_id == block_id)
        .where(AuditLog.entity_type == "GraniteBlock")
        .order_by(AuditLog.timestamp)
    )
    audits = audit_result.scalars().all()

    report = {
        "report_title": "GraniteMeasure AI — Block Assessment Report",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "report_version": "1.0",

        "block": {
            "id": block.id,
            "identifier": block.identifier,
            "color_group": block.color_group,
            "block_type": block.block_type,
            "status": block.status,
            "gps_latitude": block.gps_latitude,
            "gps_longitude": block.gps_longitude,
            "observations": block.observations,
            "registered_at": block.registered_at.isoformat() if block.registered_at else None,
        },

        "quarry": {
            "id": quarry.id,
            "name": quarry.name,
            "code": quarry.code,
            "district": quarry.district,
            "mandal": quarry.mandal,
            "village": quarry.village,
        } if quarry else None,

        "images": {
            "total_count": image_count,
        },

        "measurement": None,
        "seigniorage": None,
        "audit_trail": [],

        "disclaimer": (
            "This report is generated by GraniteMeasure AI for indicative purposes. "
            "Measurements are based on image-based reconstruction and are subject to "
            "calibration accuracy and image quality. Seigniorage rates are challenge-configured "
            "and NOT independently certified as current law. "
            "Official assessment requires authorized government verification."
        ),
    }

    if measurement:
        warnings = []
        if measurement.warnings:
            try:
                warnings = json.loads(measurement.warnings)
            except (json.JSONDecodeError, TypeError):
                warnings = [measurement.warnings]

        report["measurement"] = {
            "length_cm": measurement.length_cm,
            "breadth_cm": measurement.breadth_cm,
            "height_cm": measurement.height_cm,
            "volume_m3": measurement.volume_m3,
            "weight_mt": measurement.weight_mt,
            "confidence": measurement.confidence,
            "status": measurement.status,
            "calibration_status": measurement.calibration_status,
            "measurement_type": measurement.measurement_type,
            "reconstructed_points": measurement.reconstructed_points,
            "usable_images": measurement.usable_images,
            "warnings": warnings,
        }

    if assessment:
        report["seigniorage"] = {
            "color_group": assessment.color_group,
            "classification": assessment.classification,
            "is_above_gangsaw": assessment.is_above_gangsaw,
            "rate_per_mt": assessment.rate_per_mt,
            "weight_mt": assessment.weight_mt,
            "weight_source": assessment.weight_source,
            "indicative_amount": assessment.indicative_amount,
            "rate_version": assessment.rate_version,
            "disclaimer": assessment.disclaimer,
            "assessed_at": assessment.assessed_at.isoformat() if assessment.assessed_at else None,
        }

    report["audit_trail"] = [
        {
            "action": a.action,
            "details": a.details,
            "timestamp": a.timestamp.isoformat() if a.timestamp else None,
        }
        for a in audits
    ]

    # Audit this report generation
    audit = AuditLog(
        action="REPORT_GENERATED",
        entity_type="GraniteBlock",
        entity_id=block_id,
        details=f"Report generated for block {block.identifier}",
        timestamp=datetime.now(timezone.utc),
    )
    db.add(audit)
    await db.commit()

    return report


@router.get("/")
async def list_reports(db: AsyncSession = Depends(get_db)):
    """List blocks with available reports."""
    result = await db.execute(
        select(GraniteBlock)
        .where(GraniteBlock.status.in_(["MEASURED", "VERIFIED"]))
        .order_by(GraniteBlock.registered_at.desc())
    )
    blocks = result.scalars().all()
    return [
        {"block_id": b.id, "identifier": b.identifier, "status": b.status}
        for b in blocks
    ]
